#!/usr/bin/env python3
"""Generate `eval/fixtures/dev.log` and `eval/fixtures/runs.json`.

    python3 -I eval/make_dev_log_fixture.py           # rewrite both files
    python3 -I eval/score.py fixture-drift            # fail if they are stale

**The log this writes is SYNTHESIZED. It is not a recording of a real turn and
no number taken from it is measured.** No live turn has ever run (docs/00 §3,
§12), so there is nothing to record yet. Every record shape here is built from
the generated emitter `vaidyavaani-agent/build/livekit/utils/dev_metrics.py`,
documented in `docs/03-p0-findings.md` §14 — the emitter is the thing that
writes the real log, so the shapes are authoritative; the *timings* are
invented and the *order* is a plausible guess. The point of the file is to
prove the harness works before demo day, so that when a live turn finally runs
the only unknown is the result and not the tool.

**Why generated rather than hand-written.** The spoken strings in it are the
template render of the real `content/readback/*.yaml`. A hand-written copy goes
stale the moment a reviewer corrects a string, and the harness then reports
deviations that are nothing but the fixture rotting. docs/00 §6 records exactly
that costing two round trips. So the log is a derived artifact: regenerate it
with this script, and `score.py fixture-drift` fails loudly the moment the
committed copy and the real content disagree.

Seeded deviations, which are the point of a fixture that does not simply pass:

* `rx-07`, in all three languages — the agent paraphrases the notes clause
  instead of reading it verbatim. A real risk: `notes` is the one free-text
  field in the sentence, so it is the one an LLM is most tempted to reword.
* `rx-01` in Tamil — identical text in NFD instead of NFC, plus a doubled
  space. Byte-different, meaning-identical: it exercises the difference between
  the harness's strict and normalised counts, which is otherwise untested.
"""

from __future__ import annotations

import csv
import json
import random
import sys
import unicodedata
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import readback_render as rr  # noqa: E402

EVAL = Path(__file__).resolve().parent
FIXTURES = EVAL / "fixtures"
LANGS = ("ta", "kn", "hi")
SENTINEL = "UNMUTE_METRIC"

HEADER = """\
# eval/fixtures/dev.log — SYNTHESIZED, NOT A RECORDING.
#
# Generated by eval/make_dev_log_fixture.py from the record shapes in
# docs/03-p0-findings.md §14, which were read off the generated emitter
# build/livekit/utils/dev_metrics.py. NO LIVE TURN HAS EVER RUN (docs/00 §3),
# so every latency in here is invented and nothing taken from this file is a
# measurement. Do not quote a number from it. Do not put one on a slide.
#
# The spoken read-back strings ARE real: they are the template render of the
# real content/readback/*.yaml, produced at generation time. Regenerate after
# any content change -- `python3 -I eval/score.py fixture-drift` says when.
#
# Two deviations are seeded on purpose (a fixture where everything passes only
# proves that the harness can print "pass"):
#   rx-07, all three languages : the notes clause paraphrased, not read back
#   rx-01, Tamil               : NFD + a doubled space, byte-different only
#
# Plain log lines like this one are here deliberately: the real dev.log is the
# worker's stdout and carries both. Records are sentinel-prefixed, nested under
# a key equal to their own kind, timed in SECONDS, and revised in place.
"""


def _rx_rows() -> list[dict]:
    with (EVAL / "prescriptions.csv").open(encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        r["lines"] = json.loads(r["expected_lines_json"])
    return rows


class Call:
    """One call's worth of records, in the emitter's envelope."""

    def __init__(self, call_id: str, rng: random.Random):
        self.call_id = call_id
        self.rng = rng
        self.order = 0
        self.lines: list[str] = []

    def emit(self, kind: str, entity_id: str, payload: dict, revision: int = 1) -> None:
        if revision == 1:
            self.order += 1
        record = {
            "version": 2, "kind": kind, "call_id": self.call_id, "id": entity_id,
            "revision": revision, "order": self.order, kind: payload,
        }
        self.lines.append(f"{SENTINEL} {json.dumps(record, separators=(',', ':'), ensure_ascii=False)}")

    def log(self, text: str) -> None:
        self.lines.append(text)

    def measurement(self, entity_id: str, metric: str, source: str, value: float | None,
                    **fields) -> None:
        body = {"metric": metric, "unit": "seconds", "source": source, **fields}
        if value is None:
            # An unavailable record has NO value key at all, plus a reason.
            body["state"] = "unavailable"
        else:
            body["state"] = "measured"
            body["value"] = round(value, 3)
        self.emit("measurement", entity_id, body)

    def turn(self, response_id: str) -> None:
        """One patient turn: EOU, LLM, STT-unavailable, TTS, reply latency."""
        r = self.rng
        self.emit("exchange", response_id, {"role": "response", "state": "open",
                                            "link_status": "known"})
        self.measurement(f"{response_id}-turn_detection", "turn_detection",
                         "LiveKit EOUMetrics", r.uniform(0.18, 0.34),
                         scope="response", exchange_id=response_id,
                         reason="Native end-of-speech to end-of-turn decision.")
        self.measurement(f"{response_id}-transcription_delay", "transcription_delay",
                         "LiveKit EOUMetrics", r.uniform(0.22, 0.46),
                         scope="response", exchange_id=response_id)
        op = f"llm-{response_id}"
        self.emit("operation", op, {"type": "llm", "name": "Reasoning", "state": "ended",
                                    "exchange_id": response_id})
        ttft = r.uniform(0.19, 0.44)
        self.measurement(f"{op}-first_response", "first_response", "LiveKit LLMMetrics.ttft",
                         ttft, scope="operation", operation_id=op, exchange_id=response_id,
                         model="gpt-4o-mini", provider="openai",
                         reason="SDK first response; may precede visible answer text.")
        self.measurement(f"{op}-request_duration", "request_duration",
                         "LiveKit LLMMetrics.duration", ttft + r.uniform(0.3, 0.7),
                         scope="operation", operation_id=op, exchange_id=response_id,
                         model="gpt-4o-mini", provider="openai")
        # Saaras is streaming, so the only STT measurement is always unavailable.
        self.measurement(f"stt-{response_id}", "request_duration", "LiveKit STTMetrics.duration",
                         None, scope="unassigned",
                         reason="Streaming STT does not measure request duration.")
        tts = f"tts-{response_id}"
        ttfb = r.uniform(0.16, 0.31)
        self.measurement(f"{tts}-first_response", "first_response", "LiveKit TTSMetrics.ttfb",
                         ttfb, scope="operation", operation_id=tts, exchange_id=response_id,
                         model="sarvam/bulbul:v3", provider="slng",
                         reason="Time to first synthesized audio; not speech duration.")
        latency = ttft + ttfb + r.uniform(0.25, 0.6)
        self.measurement(f"{response_id}-reply_latency", "reply_latency", "LiveKit LLM node",
                         latency, scope="response", exchange_id=response_id)
        # Revised in place once playback confirms it — the duplicate that
        # double-counts p90 for anyone who does not dedupe by id.
        self.emit("measurement", f"{response_id}-reply_latency", {
            "metric": "reply_latency", "unit": "seconds", "source": "LiveKit playback",
            "scope": "response", "exchange_id": response_id, "state": "measured",
            "value": round(latency + 0.02, 3)}, revision=2)

    def speak(self, response_id: str, text: str, *, split: bool = False) -> None:
        """An assistant utterance. `split` emits it as two segments of one
        message, which is how the emitter reports a streamed reply."""
        if not split:
            self.emit("text", f"{response_id}-text", {
                "message_id": response_id, "speaker": "assistant", "text": text,
                "state": "final", "origin": "generated", "separator_before": "",
                "exchange_id": response_id})
            return
        cut = text.find(" ", len(text) // 2) + 1 or len(text)
        self.emit("text", f"{response_id}-text", {
            "message_id": response_id, "speaker": "assistant", "text": text[:cut].rstrip(),
            "state": "final", "origin": "generated", "separator_before": "",
            "exchange_id": response_id})
        self.emit("text", f"{response_id}-text-2", {
            "message_id": response_id, "speaker": "assistant", "text": text[cut:],
            "state": "final", "origin": "generated", "separator_before": " ",
            "exchange_id": response_id})

    def hear(self, response_id: str, text: str) -> None:
        self.emit("text", f"{response_id}-heard", {
            "message_id": response_id, "speaker": "user", "text": text,
            "state": "final", "origin": "recognition", "separator_before": ""})

    def state(self, entity_id: str, field: str, value, step: str) -> None:
        by = {"kind": "step", "name": step}
        self.emit("state", entity_id, {"origin": by, "changes": [
            {"field": field, "value": value, "by": by, "confirmed": True}]})


def _deviate_notes(text: str, lang: str) -> str:
    """Paraphrase the notes clause instead of reading it verbatim."""
    tpl = rr.load(lang)
    prefix = tpl["notes_prefix"]
    head, sep, _tail = text.partition(prefix)
    if not sep:
        return text
    paraphrase = {"ta": "வாரம் ஒரு முறை மட்டும்.",
                  "kn": "ವಾರಕ್ಕೆ ಒಂದು ಸಲ ಮಾತ್ರ.",
                  "hi": "हफ़्ते में सिर्फ़ एक बार।"}[lang]
    return head + paraphrase


def _deviate_normalisation(text: str) -> str:
    """Same sentence, different bytes: NFD and a doubled space."""
    return unicodedata.normalize("NFD", text).replace(", ", ",  ", 1)


def build() -> tuple[str, dict]:
    rng = random.Random(20261017)
    out: list[str] = [HEADER.rstrip()]
    runs: dict[str, dict] = {}

    for row in _rx_rows():
        for lang in LANGS:
            call_id = f"call_{row['id'].replace('-', '')}_{lang}"
            call = Call(call_id, rng)
            call.log(f"[worker] call {call_id} joined room vv-{row['id']}-{lang}")
            call.emit("call", "call", {"target": "livekit", "state": "open"})
            call.turn("resp_1")
            call.hear("resp_1", row["dictation"])
            call.speak("resp_1", "Right — let me read that back to the patient.")
            spoken = rr.render_prescription(row["lines"], lang)
            call.state("state-1", "readback_text", spoken, "confirm_prescription")
            call.log("[console] gate: confirmed, readback_text rendered from confirmed fields")
            call.turn("resp_2")
            if row["id"] == "rx-07":
                spoken = _deviate_notes(spoken, lang)
            elif row["id"] == "rx-01" and lang == "ta":
                spoken = _deviate_normalisation(spoken)
            call.speak("resp_2", spoken, split=len(row["lines"]) > 1)
            call.emit("call", "call", {"target": "livekit", "state": "ended",
                                       "reason": "doctor ended"}, revision=2)
            out.extend(call.lines)
            runs[call_id] = {"prescription_id": row["id"], "language": lang}

    halfstep = json.loads((FIXTURES / "halfstep_cases.json").read_text(encoding="utf-8"))
    out.append("[worker] --- half-step probes (docs/00 §7); not part of the 10 prescriptions ---")
    for case in halfstep["render_cases"]:
        for lang in halfstep["languages"]:
            call_id = f"call_{case['id'].replace('-', '')}_{lang}"
            call = Call(call_id, rng)
            call.emit("call", "call", {"target": "livekit", "state": "open"})
            call.turn("resp_1")
            spoken = rr.render_prescription([case["rx"]], lang)
            call.state("state-1", "readback_text", spoken, "confirm_prescription")
            call.speak("resp_1", spoken)
            call.emit("call", "call", {"target": "livekit", "state": "ended",
                                       "reason": "doctor ended"}, revision=2)
            out.extend(call.lines)

    runs_doc = {
        "_comment": [
            "SYNTHESIZED alongside eval/fixtures/dev.log by eval/make_dev_log_fixture.py.",
            "Not a record of real runs. The real one is written by whoever drives the 10",
            "prescription runs, and is keyed by the dev server's call_id — the dev.log has",
            "no session_id field at all (see docs/03 §14 and eval/devlog.py).",
        ],
        "source": "eval/fixtures/dev.log",
        "key": "call_id",
        "sessions": runs,
    }
    return "\n".join(out) + "\n", runs_doc


def main() -> int:
    log, runs = build()
    (FIXTURES / "dev.log").write_text(log, encoding="utf-8")
    (FIXTURES / "runs.json").write_text(json.dumps(runs, indent=2, ensure_ascii=False) + "\n",
                                        encoding="utf-8")
    print(f"wrote {FIXTURES / 'dev.log'} ({len(log.splitlines())} lines) "
          f"and {FIXTURES / 'runs.json'} ({len(runs['sessions'])} calls)")
    print("SYNTHESIZED — not a recording of a real turn, and no number from it is measured.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
